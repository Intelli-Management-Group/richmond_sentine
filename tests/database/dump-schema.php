<?php

/*
 * Writes the table structure (no data) of the local development database to
 * tests/database/schema.sql. The test suite builds its database from that file,
 * because the migrations in database/migrations no longer match the live schema.
 *
 * Run it again after the live schema changes:  composer test:schema
 */

use Illuminate\Contracts\Console\Kernel;
use Illuminate\Support\Facades\DB;

require __DIR__.'/../../vendor/autoload.php';

$app = require __DIR__.'/../../bootstrap/app.php';
$app->make(Kernel::class)->bootstrap();

$database = DB::connection()->getDatabaseName();
$tables = array_map(
    fn ($row) => $row->table_name,
    DB::select(
        "select table_name as table_name from information_schema.tables where table_schema = ? and table_type = 'BASE TABLE' order by table_name",
        [$database]
    )
);

$sql = "-- Table structure of the '{$database}' database, without data.\n";
$sql .= "-- Generated by tests/database/dump-schema.php; do not edit by hand.\n\n";

foreach ($tables as $table) {
    $create = array_values((array) DB::selectOne("show create table `{$table}`"))[1];
    $sql .= preg_replace('/ AUTO_INCREMENT=\d+/', '', $create).";\n\n";
}

file_put_contents(__DIR__.'/schema.sql', $sql);

echo 'Wrote '.count($tables)." tables from '{$database}' to tests/database/schema.sql\n";
